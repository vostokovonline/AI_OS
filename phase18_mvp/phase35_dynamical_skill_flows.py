class FlowManifold:
    """
    Manifold over dynamical skill flows.
    
    Unlike Phase 33's SkillManifold (which interpolated action vectors),
    this manifold interpolates FLOW BEHAVIORS.
    
    Similarity on this manifold = similar DYNAMICS, not similar actions.
    
    Organization principles:
      - Nearby flows produce similar trajectories from same start state
      - The manifold is a "behavior space" not an "action space"
    """
    
    def __init__(self, flow_dim: int = 8):
        self.flow_dim = flow_dim
        self.flows: Dict[str, SkillFlow] = {}
        self.flow_coords: Dict[str, np.ndarray] = {}
        
        # Learned embedding: flow parameters → manifold coordinate
        self.embedding_projection: Optional[np.ndarray] = None
    
    def add_flow(self, flow: SkillFlow, flow_id: str,
                 coord: Optional[np.ndarray] = None):
        """Add flow to manifold."""
        flow.flow_id = flow_id
        self.flows[flow_id] = flow
        
        if coord is None:
            coord = np.random.randn(self.flow_dim) * 0.5
        
        self.flow_coords[flow_id] = coord
    
    def interpolate_at(self, coord: np.ndarray,
                       world_model: Optional[MinimalWorldModel] = None,
                       z_test: Optional[np.ndarray] = None) -> ComposedFlow:
        """
        Interpolate flows at manifold coordinate.
        
        Returns a ComposedFlow that blends nearby flows weighted by:
          - inverse distance on manifold
          - flow stability
        
        This is the key operation: coordinate → blended dynamics
        """
        if not self.flows:
            return PointFlow(np.zeros(16))
        
        # Find distances
        distances = []
        for fid, c in self.flow_coords.items():
            dist = np.linalg.norm(coord - c)
            flow = self.flows[fid]
            distances.append((dist, fid, flow))
        
        distances.sort(key=lambda x: x[0])
        
        # Blend k-nearest flows
        k = min(4, len(distances))
        nearest = distances[:k]
        
        total_weight = 0.0
        weights = []
        blend_flows = []
        
        for dist, fid, flow in nearest:
            w = flow.stability / (dist + 0.1)
            weights.append(w)
            blend_flows.append(flow)
            total_weight += w
        
        if total_weight > 0:
            weights = [w / total_weight for w in weights]
        else:
            weights = [1.0 / k] * k
        
        return ComposedFlow(blend_flows, weights)
    
    def compute_similarity(self, flow_id_1: str, flow_id_2: str,
                           world_model: MinimalWorldModel,
                           z_test: np.ndarray,
                           n_steps: int = 10) -> float:
        """
        Compute behavioral similarity between two flows.
        
        Two flows are similar if they produce similar trajectories
        from the same starting state.
        
        This is the foundation for topological organization.
        """
        if flow_id_1 not in self.flows or flow_id_2 not in self.flows:
            return 0.0
        
        h = np.zeros(world_model.belief_dim)
        
        traj_1 = rollout_flow(self.flows[flow_id_1], z_test, h, world_model, n_steps)
        traj_2 = rollout_flow(self.flows[flow_id_2], z_test, h, world_model, n_steps)
        
        states_1 = traj_1['states']
        states_2 = traj_2['states']
        
        # Dynamic Time Warping-style similarity
        diffs = np.mean((states_1 - states_2) ** 2, axis=1)
        similarity = np.exp(-np.mean(diffs))
        
        return float(similarity)
    
    def organize_topology(self, world_model: MinimalWorldModel,
                          z_test: np.ndarray, n_steps: int = 10):
        """
        Reorganize manifold coordinates based on behavioral similarity.
        
        Flows with similar dynamics get moved closer together.
        This is the "topology learning" step.
        """
        if len(self.flows) < 2:
            return
        
        flow_ids = list(self.flows.keys())
        
        # Compute pairwise similarity
        n = len(flow_ids)
        sim_matrix = np.zeros((n, n))
        
        for i in range(n):
            for j in range(i + 1, n):
                sim = self.compute_similarity(
                    flow_ids[i], flow_ids[j], world_model, z_test, n_steps
                )
                sim_matrix[i, j] = sim
                sim_matrix[j, i] = sim
            sim_matrix[i, i] = 1.0
        
        # Update coordinates: similar flows → closer in manifold
        # Simple approach: MDS-style update
        for i in range(n):
            weighted_displacement = np.zeros(self.flow_dim)
            total_weight = 0.0
            
            for j in range(n):
                if i == j:
                    continue
                
                target_dist = 1.0 - sim_matrix[i, j]  # Similar → small distance
                current_dist = np.linalg.norm(
                    self.flow_coords[flow_ids[i]] - self.flow_coords[flow_ids[j]]
                )
                
                if current_dist > 1e-8:
                    direction = (self.flow_coords[flow_ids[j]] - self.flow_coords[flow_ids[i]]) / current_dist
                    displacement = direction * (current_dist - target_dist * 3.0)
                    w = sim_matrix[i, j] ** 2  # Similar flows pull harder
                    
                    weighted_displacement += w * displacement
                    total_weight += w
            
            if total_weight > 0:
                self.flow_coords[flow_ids[i]] += 0.05 * weighted_displacement / total_weight


