"""
Phase 35 — Dynamical Skill Flows

KEY SHIFT:
  BEFORE: skill = static action vector (point attractor)
          a = attractor_point  ← frozen, state-independent
  
  AFTER:  skill = local dynamical system (vector field policy)
          a_t = π_skill(z_t, h_t)  ← state-dependent, closed-loop
  
  A skill is no longer an action.
  A skill is a flow regime in state space.

FLOW TYPES:
  - PointFlow:      a = K * (z_target - z)         → converge to point
  - LimitCycleFlow:  a = ω*R*z + K*(r - |z-c|)*(z-c) → stable oscillation
  - LinearFlow:      a = A @ z + b                  → general linear dynamics
  - ComposedFlow:    a = Σ w_i * π_i(z, h)          → superposition of flows

ARCHITECTURAL IMPACT:
  Execution is no longer:  coord → action → transition
  Execution becomes:       coord → local flow → trajectory shaping
  
  This enables:
    - Temporal coordination (oscillation, phase)
    - Recovery dynamics (flow always has a direction)
    - Closed-loop correction (action depends on state)
    - Skill composition (superposition of flows)
    
  And critically:
    World model training becomes MEANINGFUL
    because trajectories are generated by persistent control dynamics,
    not by random actions or static attractors.
"""

