def rollout_flow(
    flow: SkillFlow,
    z_start: np.ndarray,
    h_start: np.ndarray,
    world_model: MinimalWorldModel,
    n_steps: int = 10,
    noise_scale: float = 0.0
) -> Dict:
    """
    Execute flow through world model for n_steps.
    
    Each step:
      1. a_t = flow.compute_action(z_t, h_t)   ← flow policy
      2. z_{t+1} = world_model(z_t, h_t, a_t)  ← world dynamics
      3. record transition
    
    Returns: full trajectory + metrics
    """
    z = z_start.copy()
    h = h_start.copy()
    
    states = [z.copy()]
    beliefs = [h.copy()]
    actions = []
    goal_probs = []
    uncertainties = []
    
    for step in range(n_steps):
        a = flow.compute_action(z, h)
        
        mu, logvar = world_model.predict_transition(z, h, a)
        
        if noise_scale > 0:
            std = np.exp(0.5 * logvar)
            z_next = mu + std * np.random.randn(*mu.shape) * noise_scale
        else:
            z_next = mu
        
        h = world_model.gru_step(h, mu)
        
        flow.record_transition(z, z_next, a, h)
        
        states.append(z_next.copy())
        beliefs.append(h.copy())
        actions.append(a.copy())
        uncertainties.append(float(np.mean(np.exp(logvar))))
        
        z = z_next.copy()
    
    return {
        'states': np.array(states),
        'beliefs': beliefs,
        'actions': np.array(actions),
        'uncertainties': uncertainties,
        'final_state': z.copy(),
        'final_belief': h.copy(),
        'n_steps': n_steps
    }


def evaluate_flow_goal(
    flow: SkillFlow,
    z_start: np.ndarray,
    h_start: np.ndarray,
    goal: GoalAttractor,
    world_model: MinimalWorldModel,
    n_steps: int = 10
) -> float:
    """
    Evaluate flow's expected goal satisfaction.
    
    Score = P(goal | trajectory) - λ * uncertainty
    """
    result = rollout_flow(flow, z_start, h_start, world_model, n_steps)
    
    z_final = result['final_state']
    dist = np.linalg.norm(z_final - goal.attractor_state[:len(z_final)])
    
    goal_prob = np.exp(-dist)
    avg_uncertainty = np.mean(result['uncertainties']) if result['uncertainties'] else 0.0
    
    return float(goal_prob - 0.1 * avg_uncertainty)


