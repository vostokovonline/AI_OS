class DynamicalSkillEngine:
    """
    Complete execution engine with dynamical skill flows.
    
    Integrates:
      Phase 30: World model
      Phase 34: Inverse dynamics  
      Phase 35: Skill flows (this phase)
    
    Execution loop:
      CEM → manifold coordinate → blended flow → rollout → 
      evaluate → stabilize → update manifold topology
    """
    
    def __init__(
        self,
        world_model: MinimalWorldModel,
        goal: GoalAttractor,
        flow_manifold: Optional[FlowManifold] = None,
        inv_dyn: Optional[InverseDynamicsModel] = None,
        n_initial_flows: int = 8,
        flow_dim: int = 8
    ):
        self.wm = world_model
        self.goal = goal
        self.flow_dim = flow_dim
        
        # Flow manifold
        self.manifold = flow_manifold or FlowManifold(flow_dim=flow_dim)
        
        # Inverse dynamics (from Phase 34)
        self.inv_dyn = inv_dyn or InverseDynamicsModel(
            latent_dim=world_model.latent_dim,
            action_dim=world_model.action_dim
        )
        
        # Adapters
        self.adapter = SkillDynamicsAdapter(world_model)
        self.evaluator = ProbabilisticGoalEvaluator(world_model)
        
        # Seed initial flows
        if not self.manifold.flows:
            self._seed_flows(n_initial_flows)
        
        # CEM
        self.cem = FlowCEM(
            world_model=self.wm,
            manifold=self.manifold,
            evaluator=self.evaluator,
            flow_dim=flow_dim
        )
        
        # Execution state
        self.execution_log: List[Dict] = []
    
    def _seed_flows(self, n: int):
        """Seed initial flow regimes."""
        for i in range(n):
            flow_type = random.choice([FlowType.POINT, FlowType.LIMIT_CYCLE, FlowType.POINT])
            
            if flow_type == FlowType.POINT:
                target = np.random.randn(self.wm.latent_dim) * 0.5
                flow = PointFlow(target, gain=random.uniform(0.2, 0.8))
            elif flow_type == FlowType.LIMIT_CYCLE:
                center = np.random.randn(self.wm.latent_dim) * 0.3
                flow = LimitCycleFlow(center, radius=random.uniform(0.5, 2.0),
                                      omega=random.uniform(0.2, 1.0))
            else:
                flow = LinearFlow(latent_dim=self.wm.latent_dim)
            
            self.manifold.add_flow(flow, f'seed_{i}')
    
    def execute_step(self, z: np.ndarray, h: np.ndarray) -> Dict:
        """
        One execution step with flow dynamics.
        
        1. CEM plans flow coordinate
        2. Flow generates action
        3. World model transitions
        4. Train inverse dynamics
        5. Update manifold topology
        """
        # 1. Plan flow
        plan = self.cem.plan_flow(z, h, self.goal)
        
        if plan['flow'] is None:
            # Fallback: nearest flow
            if self.manifold.flows:
                flow = list(self.manifold.flows.values())[0]
            else:
                flow = PointFlow(np.zeros(self.wm.latent_dim))
        else:
            flow = plan['flow']
        
        # 2. Generate action from flow
        a = flow.compute_action(z, h)
        
        # 3. Apply through world model
        mu, logvar = self.wm.predict_transition(z, h, a)
        std = np.exp(0.5 * logvar)
        z_next = mu + std * np.random.randn(*mu.shape) * 0.1
        h_next = self.wm.gru_step(h, mu)
        
        # Record
        flow.record_transition(z, z_next, a, h)
        
        # 4. Train inverse dynamics
        self.inv_dyn.train_step(z, z_next, a)
        self.inv_dyn.add_transition(z, z_next, a)
        
        # 5. Evaluate
        goal_prob = self.evaluator.goal_satisfaction_probability(self.goal, mu, logvar)
        
        # Update flow stability
        flow.stability = flow.compute_lyapunov_estimate()
        
        step_result = {
            'z_before': z.copy(),
            'z_after': z_next.copy(),
            'action': a.copy(),
            'goal_prob': float(goal_prob),
            'flow_type': flow.flow_type.value,
            'flow_id': flow.flow_id,
            'stability': flow.stability,
            'n_flows': len(self.manifold.flows)
        }
        
        self.execution_log.append(step_result)
        return step_result
    
    def execute_goal(self, z_start: np.ndarray, max_steps: int = 50) -> Dict:
        """Execute full goal with flow dynamics."""
        z = z_start.copy()
        h = np.zeros(self.wm.belief_dim)
        h = self.wm.gru_step(h, z)
        
        all_states = [z.copy()]
        goal_reached = False
        
        for step in range(max_steps):
            result = self.execute_step(z, h)
            
            if result['goal_prob'] > 0.7:
                goal_reached = True
            
            z = result['z_after'].copy()
            h = self.wm.gru_step(h, result['z_after'])
            all_states.append(z.copy())
        
        # Organize manifold topology
        if len(self.manifold.flows) >= 2 and len(all_states) > 5:
            self.manifold.organize_topology(
                self.wm, all_states[len(all_states) // 2], n_steps=5
            )
        
        # Get stability report
        stabilities = [f.stability for f in self.manifold.flows.values()]
        flow_types = [f.flow_type.value for f in self.manifold.flows.values()]
        
        return {
            'goal_reached': goal_reached,
            'final_goal_prob': self.execution_log[-1]['goal_prob'] if self.execution_log else 0.0,
            'n_steps': len(self.execution_log),
            'n_flows': len(self.manifold.flows),
            'flow_types': {t: flow_types.count(t) for t in set(flow_types)},
            'stability': {
                'mean': float(np.mean(stabilities)) if stabilities else 0.0,
                'max': float(max(stabilities)) if stabilities else 0.0,
                'min': float(min(stabilities)) if stabilities else 0.0
            },
            'execution_log': self.execution_log[-10:],
            'trajectory_length': len(all_states)
        }


