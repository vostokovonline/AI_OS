class FlowType(Enum):
    POINT = "point_attractor"
    LIMIT_CYCLE = "limit_cycle"
    LINEAR = "linear_flow"
    COMPOSED = "composed_flow"


class SkillFlow:
    """
    Base class for dynamical skill flows.
    
    A flow is a policy: π(z, h) → a
    It defines a local dynamical regime in state space.
    
    Unlike a point attractor (static action), a flow produces
    different actions depending on current state — this enables
    closed-loop control, oscillation, and recovery.
    """
    
    def __init__(self, flow_type: FlowType):
        self.flow_type = flow_type
        self.flow_id: str = ""
        
        # Stability metrics
        self.stability: float = 0.5
        self.goal_alignment: float = 0.0
        self.age: int = 0
        
        # Execution history
        self.execution_trace: List[Dict] = []
        self.max_history: int = 50
    
    def compute_action(self, z: np.ndarray, h: np.ndarray) -> np.ndarray:
        """
        π(z, h) → a
        
        The core of the flow — state-dependent action generation.
        """
        raise NotImplementedError
    
    def get_parameters(self) -> np.ndarray:
        """Get flow parameters as flat vector (for CEM)."""
        raise NotImplementedError
    
    def set_parameters(self, params: np.ndarray):
        """Set flow parameters from flat vector."""
        raise NotImplementedError
    
    def parameter_dim(self) -> int:
        """Dimension of parameter space for CEM."""
        raise NotImplementedError
    
    def record_transition(self, z_before: np.ndarray, z_after: np.ndarray,
                          a: np.ndarray, h: np.ndarray):
        """Record execution step."""
        self.execution_trace.append({
            'z_before': z_before.copy(),
            'z_after': z_after.copy(),
            'action': a.copy(),
            'h': h.copy()
        })
        if len(self.execution_trace) > self.max_history:
            self.execution_trace.pop(0)
        self.age += 1
    
    def compute_lyapunov_estimate(self) -> float:
        """
        Estimate Lyapunov exponent from execution trace.
        
        λ < 0 → stable (convergent)
        λ ≈ 0 → limit cycle (neutrally stable)
        λ > 0 → chaotic (divergent)
        
        Returns: normalized stability [0, 1] where 1 = most stable
        """
        if len(self.execution_trace) < 5:
            return self.stability
        
        deltas = np.array([
            t['z_after'] - t['z_before']
            for t in self.execution_trace[-20:]
        ])
        
        if len(deltas) < 2:
            return self.stability
        
        # Estimate expansion/contraction rate
        diffs = deltas[1:] - deltas[:-1]
        
        if np.linalg.norm(deltas[-1]) < 1e-8:
            contraction = 0.0
        else:
            contraction = np.linalg.norm(deltas[-1]) / (np.linalg.norm(deltas[0]) + 1e-8)
        
        # Normalize: 0 = divergent, 1 = convergent
        stability = 1.0 / (1.0 + max(0, contraction))
        
        return float(np.clip(stability, 0.0, 1.0))


class PointFlow(SkillFlow):
    """
    Linear point attractor: a = K * (z_target - z)
    
    Pulls the system toward a target state.
    Most common skill regime — "reach for goal."
    
    Parameters: z_target (latent_dim), K (scalar gain)
    """
    
    def __init__(self, z_target: np.ndarray, gain: float = 0.5, latent_dim: int = 16):
        super().__init__(FlowType.POINT)
        self.latent_dim = latent_dim
        self.z_target = np.asarray(z_target).flatten()[:latent_dim].copy()
        self.gain = gain
    
    def compute_action(self, z: np.ndarray, h: np.ndarray) -> np.ndarray:
        """a = K * (z_target - z)"""
        z = np.asarray(z).flatten()[:self.latent_dim]
        action = self.gain * (self.z_target - z)
        return action
    
    def get_parameters(self) -> np.ndarray:
        """[z_target (latent_dim), gain (1)]"""
        return np.concatenate([self.z_target, [self.gain]])
    
    def set_parameters(self, params: np.ndarray):
        self.z_target = params[:self.latent_dim].copy()
        self.gain = float(params[self.latent_dim])
    
    def parameter_dim(self) -> int:
        return self.latent_dim + 1
    
    def __repr__(self) -> str:
        return (f"PointFlow(target_norm={np.linalg.norm(self.z_target):.2f}, "
                f"gain={self.gain:.2f})")


class LimitCycleFlow(SkillFlow):
    """
    Stable limit cycle: oscillation around a center.
    
    Tangential component: ω * R_90 * (z - center)  → rotation
    Radial component:    K * (r - |z-c|) * (z-c)   → radial stability
    
    This represents oscillatory skills like:
      walking, swimming, periodic sampling, rhythmic behaviors
    
    Parameters: center (latent_dim), radius (1), omega (1), K_radial (1)
    """
    
    def __init__(self, center: np.ndarray, radius: float = 1.0,
                 omega: float = 0.5, K_radial: float = 0.3,
                 latent_dim: int = 16):
        super().__init__(FlowType.LIMIT_CYCLE)
        self.latent_dim = latent_dim
        self.center = np.asarray(center).flatten()[:latent_dim].copy()
        self.radius = radius
        self.omega = omega
        self.K_radial = K_radial
        
        # 90-degree rotation matrix (tangential direction)
        self.R = np.zeros((latent_dim, latent_dim))
        for i in range(latent_dim - 1):
            self.R[i, i + 1] = 1.0
            self.R[i + 1, i] = -1.0
    
    def compute_action(self, z: np.ndarray, h: np.ndarray) -> np.ndarray:
        """a = ω * R * (z - c) + K * (r - |z-c|) * (z-c) / |z-c|"""
        z = np.asarray(z).flatten()[:self.latent_dim]
        diff = z - self.center
        dist = np.linalg.norm(diff)
        
        if dist < 1e-8:
            diff_unit = np.zeros(self.latent_dim)
        else:
            diff_unit = diff / dist
        
        # Tangential (rotational)
        tangential = self.omega * self.R @ diff
        
        # Radial (stabilization toward radius)
        radial = self.K_radial * (self.radius - dist) * diff_unit
        
        return tangential + radial
    
    def get_parameters(self) -> np.ndarray:
        """[center (latent_dim), radius (1), omega (1), K_radial (1)]"""
        return np.concatenate([self.center, [self.radius, self.omega, self.K_radial]])
    
    def set_parameters(self, params: np.ndarray):
        self.center = params[:self.latent_dim].copy()
        self.radius = float(params[self.latent_dim])
        self.omega = float(params[self.latent_dim + 1])
        self.K_radial = float(params[self.latent_dim + 2])
    
    def parameter_dim(self) -> int:
        return self.latent_dim + 3
    
    def __repr__(self) -> str:
        return (f"LimitCycle(center_norm={np.linalg.norm(self.center):.2f}, "
                f"r={self.radius:.2f}, ω={self.omega:.2f})")


class LinearFlow(SkillFlow):
    """
    General linear dynamics: a = A @ z + b
    
    Can represent:
      - Exponential decay (negative eigenvalues)
      - Oscillation (complex eigenvalues)  
      - Growth (positive eigenvalues)
      - Fixed point shifts (bias term)
    
    Parameters: A (latent_dim × latent_dim), b (latent_dim)
    """
    
    def __init__(self, latent_dim: int = 16):
        super().__init__(FlowType.LINEAR)
        self.latent_dim = latent_dim
        
        # Initialize as stable (negative diagonal)
        scale = 0.1
        self.A = -np.eye(latent_dim) * scale + np.random.randn(latent_dim, latent_dim) * scale * 0.3
        self.b = np.zeros(latent_dim)
    
    def compute_action(self, z: np.ndarray, h: np.ndarray) -> np.ndarray:
        """a = A @ z + b"""
        z = np.asarray(z).flatten()[:self.latent_dim]
        return self.A @ z + self.b
    
    def get_parameters(self) -> np.ndarray:
        """[A.flatten (latent_dim²), b (latent_dim)]"""
        return np.concatenate([self.A.flatten(), self.b])
    
    def set_parameters(self, params: np.ndarray):
        A_size = self.latent_dim * self.latent_dim
        self.A = params[:A_size].reshape(self.latent_dim, self.latent_dim)
        self.b = params[A_size:].copy()
    
    def parameter_dim(self) -> int:
        return self.latent_dim * self.latent_dim + self.latent_dim


class ComposedFlow(SkillFlow):
    """
    Superposition of multiple flows: a = Σ w_i * π_i(z, h)
    
    This is how skills compose — by blending their vector fields.
    Composition enables complex behaviors from simple primitives.
    """
    
    def __init__(self, flows: List[SkillFlow], weights: Optional[List[float]] = None):
        super().__init__(FlowType.COMPOSED)
        self.flows = flows
        self.weights = weights or [1.0 / len(flows)] * len(flows)
    
    def compute_action(self, z: np.ndarray, h: np.ndarray) -> np.ndarray:
        """a = Σ w_i * π_i(z, h)"""
        actions = [w * f.compute_action(z, h) for w, f in zip(self.weights, self.flows)]
        return sum(actions)
    
    def get_parameters(self) -> np.ndarray:
        return np.array(self.weights)
    
    def set_parameters(self, params: np.ndarray):
        self.weights = params.tolist()
    
    def parameter_dim(self) -> int:
        return len(self.flows)


