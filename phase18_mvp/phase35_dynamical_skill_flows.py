class FlowCEM:
    """
    CEM planner over flow parameter space.
    
    NOT discrete skill indices.
    NOT action vectors.
    
    Samples FLOW PARAMETERS → evaluates trajectory via world model.
    
    The key insight: CEM now optimizes DYNAMICAL REGIMES,
    not individual actions or discrete skills.
    """
    
    def __init__(
        self,
        world_model: MinimalWorldModel,
        manifold: FlowManifold,
        evaluator: ProbabilisticGoalEvaluator,
        flow_dim: int = 8,
        n_candidates: int = 80,
        n_elites: int = 16,
        n_iterations: int = 5,
        stability_bonus: float = 0.2,
        entropy_coeff: float = 0.05,
        rollout_steps: int = 8
    ):
        self.wm = world_model
        self.manifold = manifold
        self.evaluator = evaluator
        self.flow_dim = flow_dim
        self.n_candidates = n_candidates
        self.n_elites = n_elites
        self.n_iterations = n_iterations
        self.stability_bonus = stability_bonus
        self.entropy_coeff = entropy_coeff
        self.rollout_steps = rollout_steps
        
        self.mean = np.zeros(flow_dim)
        self.std = np.ones(flow_dim)
    
    def plan_flow(
        self,
        z_start: np.ndarray,
        h_start: np.ndarray,
        goal: GoalAttractor
    ) -> Dict:
        """
        Plan flow by optimizing manifold coordinate.
        
        Returns: {coord, flow, score, trajectory}
        """
        if not self.manifold.flows:
            return {'coord': np.zeros(self.flow_dim), 'flow': None,
                    'score': -np.inf, 'trajectory': None}
        
        self.mean = np.zeros(self.flow_dim)
        self.std = np.ones(self.flow_dim)
        
        best_coord = None
        best_score = -np.inf
        best_trajectory = None
        
        for iteration in range(self.n_iterations):
            # Sample candidate manifold coordinates
            candidates = []
            for _ in range(self.n_candidates):
                coord = self.mean + self.std * np.random.randn(self.flow_dim)
                candidates.append(coord)
            
            # Evaluate each coordinate
            scores = []
            trajectories = []
            for coord in candidates:
                flow = self.manifold.interpolate_at(coord, self.wm, z_start)
                result = rollout_flow(flow, z_start, h_start, self.wm, self.rollout_steps)
                
                # Score = goal probability + stability bonus - uncertainty penalty
                z_final = result['final_state']
                dist = np.linalg.norm(z_final - goal.attractor_state[:len(z_final)])
                goal_prob = np.exp(-dist)
                
                # Stability of constituent flows
                avg_stability = np.mean([f.stability for f in flow.flows])
                
                # Uncertainty
                avg_uncertainty = np.mean(result['uncertainties']) if result['uncertainties'] else 0.0
                
                score = (goal_prob
                         + self.stability_bonus * avg_stability
                         - 0.1 * avg_uncertainty)
                
                scores.append(score)
                trajectories.append(result)
            
            # Select elites
            elite_indices = np.argsort(scores)[-self.n_elites:]
            elite_coords = [candidates[i] for i in elite_indices]
            
            # Update distribution
            if elite_coords:
                self.mean = np.mean(elite_coords, axis=0)
                self.std = np.std(elite_coords, axis=0) + 0.1
            
            # Track best
            max_idx = int(np.argmax(scores))
            if scores[max_idx] > best_score:
                best_score = scores[max_idx]
                best_coord = candidates[max_idx]
                best_trajectory = trajectories[max_idx]
        
        if best_coord is None:
            return {'coord': np.zeros(self.flow_dim), 'flow': None,
                    'score': -np.inf, 'trajectory': None}
        
        best_flow = self.manifold.interpolate_at(best_coord, self.wm, z_start)
        
        return {
            'coord': best_coord,
            'flow': best_flow,
            'score': float(best_score),
            'trajectory': best_trajectory
        }


