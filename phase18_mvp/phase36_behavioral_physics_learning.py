class BehavioralPhysicsLearner:
    """
    Manages the closed-loop training process.
    
    Loop:
      Phase 35 engine → execute → collect trajectories →
      train world model → train inverse dynamics →
      reorganize manifold → Phase 35 engine (improved)
    
    Validation:
      Before/after training: does prediction error on
      held-out flow trajectories decrease?
    """
    
    def __init__(
        self,
        world_model: FlowConditionedWorldModel,
        inv_dyn: InverseDynamicsModel,
        manifold: FlowManifold,
        goal: GoalAttractor,
        learning_rate: float = 0.01,
        k_steps: int = 5,
        batch_size: int = 16,
        seq_len: int = 10
    ):
        self.wm = world_model
        self.inv_dyn = inv_dyn
        self.manifold = manifold
        self.goal = goal
        self.lr = learning_rate
        self.k_steps = k_steps
        self.batch_size = batch_size
        self.seq_len = seq_len
        
        # Experience buffer
        self.buffer = FlowTrajectoryBuffer(max_episodes=200)
        
        # Training state
        self.training_step = 0
        self.loss_history: List[float] = []
        self.val_history: List[float] = []
        
        # Validation episodes (held out)
        self.val_episodes: List[FlowEpisode] = []
    
    def record_episode(self, episode: FlowEpisode):
        """Record episode and optionally reserve for validation."""
        if len(self.val_episodes) < 10 and random.random() < 0.2:
            self.val_episodes.append(episode)
        else:
            self.buffer.add_episode(episode)
    
    def record_from_engine(
        self,
        engine_log: List[Dict],
        flows_used: List[SkillFlow],
        states: List[np.ndarray],
        beliefs: List[np.ndarray]
    ):
        """Record episode from DynamicalSkillEngine execution."""
        if not engine_log:
            return
        
        actions = []
        rewards = []
        step_flows = []
        
        for entry in engine_log:
            a = entry.get('action', np.zeros(self.wm.action_dim))
            r = entry.get('goal_prob', 0.0)
            actions.append(a)
            rewards.append(r)
            
            # Find the flow that generated this action
            flow_id = entry.get('flow_id', '')
            flow = self.manifold.flows.get(flow_id)
            if flow is None and self.manifold.flows:
                flow = list(self.manifold.flows.values())[0]
            step_flows.append(flow or PointFlow(np.zeros(self.wm.latent_dim)))
        
        if len(states) != len(actions) + 1:
            # Align: states is one longer than actions
            pass
        
        episode = FlowEpisode(
            states=[s.copy() for s in states[:len(actions)]],
            beliefs=[b.copy() for b in beliefs[:len(actions)]],
            actions=[a.copy() for a in actions],
            flow_embeddings=[
                self.wm.compute_flow_embedding(f) for f in step_flows
            ],
            rewards=rewards,
            flow_ids=[f.flow_id for f in step_flows],
            flow_types=[f.flow_type.value for f in step_flows]
        )
        
        self.record_episode(episode)
    
    def train_step(self) -> Dict:
        """
        One training step on flow-conditioned trajectories.
        
        1. Sample batch from buffer (with flow embeddings)
        2. Compute sequence loss (flow-conditioned)
        3. Update world model weights
        4. Update inverse dynamics
        """
        if len(self.buffer.episodes) < 2:
            return {'loss': float('inf'), 'status': 'insufficient_data'}
        
        batch = self.buffer.sample_batch(self.batch_size, self.seq_len)
        
        if not batch:
            return {'loss': float('inf'), 'status': 'empty_batch'}
        
        # Compute losses
        seq_loss = compute_flow_sequence_loss(self.wm, batch, self.k_steps)
        rew_loss = compute_flow_reward_loss(self.wm, batch)
        
        total_loss = seq_loss + 0.5 * rew_loss
        
        # Gradient update (simple SGD on all params)
        # Approximate gradients via finite differences on sample
        self._apply_gradient_update(total_loss, batch)
        
        self.training_step += 1
        self.loss_history.append(float(total_loss))
        
        return {
            'loss': float(total_loss),
            'seq_loss': float(seq_loss),
            'rew_loss': float(rew_loss),
            'n_batch': len(batch),
            'step': self.training_step
        }
    
    def _apply_gradient_update(self, loss: float, batch: List[Dict]):
        """
        Apply gradient update using Evolution Strategies (ES) gradient.
        
        ES estimates ∇_θ E[f(θ)] ≈ (1/N) * Σ (f(θ + σ*ε_i) - f(θ)) / σ * ε_i
        
        This is O(N) forward passes per step (N=16) instead of
        O(num_params) which would be thousands.
        """
        n_samples = 16
        sigma = 0.01
        lr = self.lr
        
        # Collect all parameters as a list of views
        param_list = [
            self.wm.W_t1, self.wm.b_t1,
            self.wm.W_t2, self.wm.b_t2,
            self.wm.W_t_logvar, self.wm.b_t_logvar,
            self.wm.W_zh, self.wm.W_zx, self.wm.b_z,
            self.wm.W_rh, self.wm.W_rx, self.wm.b_r,
            self.wm.W_hh, self.wm.W_hx, self.wm.b_h,
            self.wm.W_mu, self.wm.b_mu,
            self.wm.W_logvar, self.wm.b_logvar,
            self.wm.W_r1, self.wm.b_r1,
            self.wm.W_r2, self.wm.b_r2,
        ]
        
        # Store original parameters
        orig_params = [p.copy() for p in param_list]
        
        # ES gradient estimation
        grad_accum = [np.zeros_like(p) for p in param_list]
        
        for k in range(n_samples):
            # Generate random perturbations
            noises = [np.random.randn(*p.shape) * sigma for p in param_list]
            
            # Positive perturbation: θ + σ*ε
            for p, n in zip(param_list, noises):
                p[:] = p + n
            loss_pos = self._eval_loss(batch)
            
            # Negative perturbation: θ - σ*ε  
            for p, n in zip(param_list, noises):
                p[:] = p - 2 * n
            loss_neg = self._eval_loss(batch)
            
            # Gradient estimate: (f(θ+σ*ε) - f(θ-σ*ε)) / (2*σ) * ε
            delta = (loss_pos - loss_neg) / (2.0 * sigma)
            for g, n in zip(grad_accum, noises):
                g[:] = g + delta * n
            
            # Restore original parameters
            for p, orig in zip(param_list, orig_params):
                p[:] = orig
        
        # Average and apply update
        for p, g in zip(param_list, grad_accum):
            p[:] = p - lr * g / n_samples
    
    def _eval_loss(self, batch: List[Dict]) -> float:
        """Evaluate loss on batch (used for gradient estimation)."""
        seq_loss = compute_flow_sequence_loss(self.wm, batch, self.k_steps)
        rew_loss = compute_flow_reward_loss(self.wm, batch)
        return float(seq_loss + 0.5 * rew_loss)
    
    def validate(self) -> Dict:
        """Validate on held-out flow episodes."""
        if not self.val_episodes:
            return {'val_loss': float('inf')}
        
        val_batch = []
        for ep in self.val_episodes[:5]:
            if ep.length >= self.k_steps + 2:
                val_batch.append({
                    'x_seq': ep.states[:self.seq_len],
                    'a_seq': ep.actions[:self.seq_len],
                    'r_seq': ep.rewards[:self.seq_len],
                    'flow_embeds': ep.flow_embeddings[:self.seq_len],
                    'flow_ids': ep.flow_ids[:self.seq_len]
                })
        
        if not val_batch:
            return {'val_loss': float('inf')}
        
        loss = compute_flow_sequence_loss(self.wm, val_batch, self.k_steps)
        self.val_history.append(float(loss))
        
        return {
            'val_loss': float(loss),
            'n_val_episodes': len(val_batch),
            'n_total_episodes': len(self.val_episodes)
        }
    
    def get_training_report(self) -> Dict:
        """Report on training progress."""
        report = {
            'training_steps': self.training_step,
            'buffer_episodes': len(self.buffer.episodes),
            'buffer_transitions': self.buffer.total_transitions,
            'val_episodes': len(self.val_episodes),
        }
        
        if self.loss_history:
            recent = self.loss_history[-min(20, len(self.loss_history)):]
            report['recent_loss'] = float(np.mean(recent))
            report['initial_loss'] = float(self.loss_history[0])
            report['loss_improvement'] = (
                (self.loss_history[0] - recent[-1]) / max(1e-8, self.loss_history[0])
                if len(self.loss_history) > 1 else 0.0
            )
        
        if self.val_history:
            report['val_loss'] = float(self.val_history[-1])
        
        if self.buffer.episodes:
            report['flow_distribution'] = self.buffer.get_flow_distribution()
        
        return report


