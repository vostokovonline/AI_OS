class ClosedLoopEngine:
    """
    Full closed-loop: execution ↔ training ↔ improvement.
    
    Integrates:
      Phase 35: DynamicalSkillEngine (flows)
      Phase 36: BehavioralPhysicsLearner (training)
    
    Loop per cycle:
      1. Execute goal with flows (Phase 35)
      2. Record trajectories (Phase 36 buffer)
      3. Train world model on flow data
      4. Train inverse dynamics
      5. Reorganize manifold
      6. Repeat with improved model
    """
    
    def __init__(
        self,
        world_model: FlowConditionedWorldModel,
        goal: GoalAttractor,
        manifold: Optional[FlowManifold] = None,
        n_initial_flows: int = 10,
        flow_dim: int = 8,
        learning_rate: float = 0.01,
        k_steps: int = 5,
        train_every_n_steps: int = 10
    ):
        self.wm = world_model
        self.goal = goal
        self.flow_dim = flow_dim
        
        # Inverse dynamics (Phase 34)
        self.inv_dyn = InverseDynamicsModel(
            latent_dim=world_model.latent_dim,
            action_dim=world_model.action_dim,
            learning_rate=0.01
        )
        
        # Manifold (Phase 35)
        self.manifold = manifold or FlowManifold(flow_dim=flow_dim)
        
        # Learner (this phase)
        self.learner = BehavioralPhysicsLearner(
            world_model=world_model,
            inv_dyn=self.inv_dyn,
            manifold=self.manifold,
            goal=goal,
            learning_rate=learning_rate,
            k_steps=k_steps
        )
        
        # Execution engine (Phase 35)
        self.engine = DynamicalSkillEngine(
            world_model=world_model,
            goal=goal,
            flow_manifold=self.manifold,
            inv_dyn=self.inv_dyn,
            n_initial_flows=0,
            flow_dim=flow_dim
        )
        
        # Seed flows
        if not self.manifold.flows:
            self._seed_flows(n_initial_flows)
        
        self.train_every_n = train_every_n_steps
        self.total_steps = 0
        self.cycle_log: List[Dict] = []
    
    def _seed_flows(self, n: int):
        """Seed initial flows in manifold."""
        for i in range(n):
            if random.random() < 0.6:
                target = np.random.randn(self.wm.latent_dim) * random.uniform(-1, 1) * 0.5
                flow = PointFlow(target, gain=random.uniform(0.2, 0.8))
            else:
                center = np.random.randn(self.wm.latent_dim) * 0.3
                flow = LimitCycleFlow(center, radius=random.uniform(0.5, 2.0),
                                      omega=random.uniform(0.2, 1.0))
            self.manifold.add_flow(flow, f'flow_{i}')
    
    def run_cycle(self, z_start: np.ndarray, n_steps: int = 20) -> Dict:
        """
        One closed-loop cycle.
        
        1. Execute with current flows (Phase 35)
        2. Record trajectories (Phase 36 buffer) with proper beliefs
        3. Train world model on flow data
        4. Report metrics
        """
        # Execute
        result = self.engine.execute_goal(z_start, max_steps=n_steps)
        
        # Reconstruct trajectory with beliefs from execution
        log = result.get('execution_log', [])
        states = [z_start.copy()]
        beliefs = [np.zeros(self.wm.belief_dim)]
        for entry in log:
            h = self.wm.gru_step(beliefs[-1], entry['z_before'])
            beliefs.append(h.copy())
            if 'z_after' in entry:
                states.append(entry['z_after'].copy())
            else:
                states.append(entry['z_before'].copy())
        
        if log:
            self.learner.record_from_engine(
                log,
                list(self.manifold.flows.values()),
                states,
                beliefs
            )
        
        # Train periodically
        train_result = {}
        if self.total_steps % self.train_every_n == 0:
            # Train for multiple steps
            train_losses = []
            for _ in range(5):
                tr = self.learner.train_step()
                if tr['loss'] != float('inf'):
                    train_losses.append(tr['loss'])
            
            if train_losses:
                train_result = {
                    'train_loss': float(np.mean(train_losses)),
                    'loss_trend': (train_losses[0] - train_losses[-1]) / max(1e-8, train_losses[0])
                }
            
            # Validate
            val = self.learner.validate()
            train_result['val_loss'] = val.get('val_loss', float('inf'))
        
        # Inverse dynamics training
        inv_loss = 0.0
        if len(self.inv_dyn.training_data) > 10:
            inv_loss = self.inv_dyn.train_from_buffer(
                self.inv_dyn.training_data[-100:]
            )
        
        self.total_steps += n_steps
        
        cycle_result = {
            'cycle': len(self.cycle_log),
            'goal_reached': result['goal_reached'],
            'goal_prob': result['final_goal_prob'],
            'n_flows': result['n_flows'],
            'stability': result['stability'],
            'training': train_result,
            'inv_dyn_loss': float(inv_loss),
            'buffer_stats': self.learner.buffer.get_stats() if hasattr(self.learner.buffer, 'get_stats') else {}
        }
        
        self.cycle_log.append(cycle_result)
        return cycle_result
    
    def run_multi_cycle(self, z_start: np.ndarray,
                        n_cycles: int = 5,
                        steps_per_cycle: int = 20,
                        carry_state: bool = True) -> Dict:
        """Run multiple closed-loop cycles with state carrying."""
        z = z_start.copy()
        
        for cycle in range(n_cycles):
            result = self.run_cycle(z, n_steps=steps_per_cycle)
            
            # Carry final state forward to next cycle
            if carry_state and self.cycle_log:
                last_z = self.engine.execution_log[-1]['z_after'] if self.engine.execution_log else None
                if last_z is not None:
                    z = last_z.copy()
        
        # Final report
        training_report = self.learner.get_training_report()
        
        goals_reached = sum(1 for c in self.cycle_log if c['goal_reached'])
        
        return {
            'n_cycles': n_cycles,
            'total_steps': self.total_steps,
            'goals_reached': goals_reached,
            'goal_rate': goals_reached / max(1, n_cycles),
            'training': training_report,
            'cycle_log': self.cycle_log[-5:]
        }


