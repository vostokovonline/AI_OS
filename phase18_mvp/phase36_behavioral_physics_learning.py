@dataclass
class FlowEpisode:
    """Complete trajectory episode with flow metadata."""
    states: List[np.ndarray]       # Latent states z_t
    beliefs: List[np.ndarray]      # Belief states h_t
    actions: List[np.ndarray]      # Actions a_t
    flow_embeddings: List[np.ndarray]  # Flow embeddings π_t
    rewards: List[float]           # Rewards r_t
    flow_ids: List[str]            # Which flows were active
    flow_types: List[str]          # Flow type names
    goal_id: str = ""              # Goal context
    goal_embedding: Optional[np.ndarray] = None
    timestamp: float = 0.0
    
    @property
    def length(self) -> int:
        return len(self.states)


class FlowTrajectoryBuffer:
    """
    Stores trajectory episodes generated by skill flows.
    
    Key difference from Phase 30 buffer:
      - Stores flow metadata (flow type, embedding, active flow)
      - Enables flow-conditioned training
      - Tracks which flow regime generated each transition
    """
    
    def __init__(self, max_episodes: int = 200):
        self.episodes: List[FlowEpisode] = []
        self.max_episodes = max_episodes
        self.total_transitions = 0
        
        # Per-flow statistics
        self.flow_stats: Dict[str, Dict] = defaultdict(lambda: {
            'n_transitions': 0,
            'total_reward': 0.0,
            'avg_uncertainty': 0.0
        })
    
    def add_episode(self, episode: FlowEpisode):
        """Add flow-generated episode."""
        self.episodes.append(episode)
        self.total_transitions += episode.length
        
        # Update per-flow stats
        for fid in set(episode.flow_ids):
            self.flow_stats[fid]['n_transitions'] += 1
        
        # Keep buffer bounded
        if len(self.episodes) > self.max_episodes:
            self.episodes = self.episodes[-self.max_episodes:]
    
    def add_from_execution(
        self,
        states: List[np.ndarray],
        beliefs: List[np.ndarray],
        actions: List[np.ndarray],
        flows: List[SkillFlow],
        rewards: Optional[List[float]] = None,
        goal: Optional[GoalAttractor] = None
    ):
        """Add episode from execution engine."""
        if rewards is None:
            rewards = [0.0] * len(states)
        
        flow_embeddings = [f.compute_flow_embedding(f) if hasattr(f, 'compute_flow_embedding') 
                          else np.zeros(8) for f in flows]
        flow_ids = [f.flow_id for f in flows]
        flow_types = [f.flow_type.value for f in flows]
        
        # Actually, flow embedding needs FlowConditionedWorldModel
        # Let's store raw flows for later embedding computation
        episode = FlowEpisode(
            states=[s.copy() for s in states],
            beliefs=[b.copy() for b in beliefs],
            actions=[a.copy() for a in actions],
            flow_embeddings=flow_embeddings,
            rewards=rewards,
            flow_ids=flow_ids,
            flow_types=flow_types,
            goal_id=goal.goal_id if goal else "",
            goal_embedding=goal.attractor_state.copy() if goal else None
        )
        
        self.add_episode(episode)
    
    def sample_batch(self, batch_size: int = 16,
                     seq_len: int = 10) -> List[Dict]:
        """
        Sample batch of sequences with flow conditioning.
        
        Returns: list of {x_seq, a_seq, r_seq, flow_embeds, flow_ids}
        """
        if not self.episodes:
            return []
        
        batch = []
        for _ in range(batch_size):
            ep = random.choice(self.episodes)
            
            if ep.length <= seq_len:
                batch.append({
                    'x_seq': ep.states,
                    'a_seq': ep.actions,
                    'r_seq': ep.rewards,
                    'flow_embeds': ep.flow_embeddings,
                    'flow_ids': ep.flow_ids
                })
                continue
            
            start = random.randint(0, ep.length - seq_len - 1)
            batch.append({
                'x_seq': ep.states[start:start + seq_len],
                'a_seq': ep.actions[start:start + seq_len],
                'r_seq': ep.rewards[start:start + seq_len],
                'flow_embeds': ep.flow_embeddings[start:start + seq_len],
                'flow_ids': ep.flow_ids[start:start + seq_len]
            })
        
        return batch
    
    def get_flow_distribution(self) -> Dict:
        """Get distribution of flows in buffer."""
        flow_counts = defaultdict(int)
        for ep in self.episodes:
            for fid in set(ep.flow_ids):
                flow_counts[fid] += 1
        return dict(flow_counts)
    
    def get_stats(self) -> Dict:
        """Buffer statistics."""
        if not self.episodes:
            return {'n_episodes': 0, 'n_transitions': 0}
        
        lengths = [ep.length for ep in self.episodes]
        return {
            'n_episodes': len(self.episodes),
            'n_transitions': self.total_transitions,
            'avg_length': float(np.mean(lengths)),
            'n_flow_types': len(self.get_flow_distribution())
        }


