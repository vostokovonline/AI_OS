# 3. FLOW-CONDITIONED SEQUENCE LOSS
# ============================================================================

def compute_flow_sequence_loss(
    model: FlowConditionedWorldModel,
    batch: List[Dict],
    k_steps: int = 5
) -> float:
    """
    Multi-step sequence loss with flow conditioning.
    
    For each timestep t:
      1. Encode observation → z_t
      2. Predict k steps using flow-conditioned transition
      3. Compare with actual encoded latents
    
    This teaches the model that dynamics depend on active flow.
    """
    total_loss = 0.0
    n_samples = 0
    
    for sample in batch:
        x_seq = sample['x_seq']
        a_seq = sample['a_seq']
        flow_embeds = sample.get('flow_embeds', [None] * len(x_seq))
        
        seq_len = len(x_seq)
        if seq_len < k_steps + 2:
            continue
        
        # Full forward pass to get true latents
        h = np.zeros(model.belief_dim)
        true_mus = []
        beliefs = []
        
        for t in range(seq_len):
            h = model.gru_step(h, x_seq[t])
            _, mu, _ = model.encode_latent(h, sample=False)
            true_mus.append(mu)
            beliefs.append(h.copy())
        
        # Multi-step prediction loss
        for t in range(seq_len - k_steps):
            z_t = true_mus[t]
            h_t = beliefs[t]
            
            z_pred = z_t.copy()
            h_pred = h_t.copy()
            
            for i in range(k_steps):
                a = a_seq[t + i]
                
                # Get flow embedding at this step
                if flow_embeds[t + i] is not None:
                    flow_embed = flow_embeds[t + i]
                else:
                    flow_embed = np.zeros(model.flow_embed_dim)
                
                # Flow-conditioned prediction
                mu_pred, logvar_pred = model.predict_transition_flow(
                    z_pred, h_pred, a, flow_embed
                )
                
                z_true = true_mus[t + i + 1]
                
                loss_step = np.mean((mu_pred - z_true) ** 2)
                loss_unc = np.mean(np.exp(logvar_pred))
                
                total_loss += loss_step + 0.01 * loss_unc
                n_samples += 1
                
                z_pred = mu_pred
                h_pred = model.gru_step(h_pred, mu_pred)
    
    return total_loss / max(1, n_samples)


def compute_flow_reward_loss(
    model: FlowConditionedWorldModel,
    batch: List[Dict]
) -> float:
    """Reward prediction loss for flow-conditioned training."""
    total_loss = 0.0
    n_samples = 0
    
    for sample in batch:
        x_seq = sample['x_seq']
        r_seq = sample['r_seq']
        
        h = np.zeros(model.belief_dim)
        
        for t in range(len(x_seq)):
            h = model.gru_step(h, x_seq[t])
            z, _, _ = model.encode_latent(h, sample=False)
            
            r_pred = model.predict_reward(z, h)
            r_true = r_seq[t]
            
            total_loss += (r_pred - r_true) ** 2
            n_samples += 1
    
    return total_loss / max(1, n_samples)


