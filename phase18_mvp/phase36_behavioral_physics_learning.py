class FlowConditionedWorldModel(MinimalWorldModel):
    """
    World model that conditions on active flow regime.
    
    Standard:   P(z_{t+1} | z_t, h_t, a_t)
    Extended:   P(z_{t+1} | z_t, h_t, a_t, π_embedding)
    
    π_embedding encodes the active flow's dynamical signature.
    This lets the model learn that different flow regimes
    produce different dynamics.
    """
    
    def __init__(self, event_dim: int = 32, latent_dim: int = 16,
                 belief_dim: int = 64, action_dim: int = 16,
                 flow_embed_dim: int = 8):
        super().__init__(event_dim, latent_dim, belief_dim, action_dim)
        
        self.flow_embed_dim = flow_embed_dim
        
        # Extended transition model with flow conditioning
        trans_input = latent_dim + belief_dim + action_dim + flow_embed_dim
        scale = 0.1
        
        # Re-initialize transition with flow conditioning
        self.W_t1 = np.random.randn(64, trans_input) * scale
        self.b_t1 = np.zeros(64)
        self.W_t2 = np.random.randn(latent_dim, 64) * scale
        self.b_t2 = np.zeros(latent_dim)
        self.W_t_logvar = np.random.randn(latent_dim, 64) * scale * 0.5
        self.b_t_logvar = np.zeros(latent_dim) - 1.0
    
    def predict_transition(
        self, z: np.ndarray, h: np.ndarray, a: np.ndarray
    ) -> Tuple[np.ndarray, np.ndarray]:
        """
        Override: predict with zero flow embedding (default/unknown flow).
        Ensures downstream code (rollout_flow, CEM) works without change.
        """
        flow_embed = np.zeros(self.flow_embed_dim)
        return self.predict_transition_flow(z, h, a, flow_embed)

    def predict_transition_flow(
        self, z: np.ndarray, h: np.ndarray,
        a: np.ndarray, flow_embed: np.ndarray
    ) -> Tuple[np.ndarray, np.ndarray]:
        """
        Predict next latent conditioned on flow.
        
        P(z_{t+1} | z_t, h_t, a_t, π)
        """
        z = np.asarray(z).flatten()[:self.latent_dim]
        h = np.asarray(h).flatten()[:self.belief_dim]
        a = np.asarray(a).flatten()[:self.action_dim]
        flow_embed = np.asarray(flow_embed).flatten()[:self.flow_embed_dim]
        
        if len(a) < self.action_dim:
            a = np.pad(a, (0, self.action_dim - len(a)))
        if len(flow_embed) < self.flow_embed_dim:
            flow_embed = np.pad(flow_embed, (0, self.flow_embed_dim - len(flow_embed)))
        
        x = np.concatenate([z, h, a, flow_embed])
        
        hidden = np.tanh(self.W_t1 @ x + self.b_t1)
        mu = self.W_t2 @ hidden + self.b_t2
        logvar = self.W_t_logvar @ hidden + self.b_t_logvar
        
        return mu, logvar
    
    def compute_flow_embedding(self, flow: SkillFlow) -> np.ndarray:
        """
        Encode flow into a fixed embedding vector.
        
        Captures the dynamical signature of the flow:
          - flow type
          - key parameters
          - stability
        """
        params = flow.get_parameters()
        
        # Normalize to flow_embed_dim
        embed = np.zeros(self.flow_embed_dim)
        
        # Type encoding
        type_code = {
            'point_attractor': np.array([1.0, 0.0, 0.0, 0.0]),
            'limit_cycle': np.array([0.0, 1.0, 0.0, 0.0]),
            'linear_flow': np.array([0.0, 0.0, 1.0, 0.0]),
            'composed_flow': np.array([0.0, 0.0, 0.0, 1.0]),
        }
        type_vec = type_code.get(flow.flow_type.value, np.zeros(4))
        
        # Stability
        stab_vec = np.array([flow.stability, flow.goal_alignment])
        
        # Parameter stats (mean, std)
        param_mean = float(np.mean(params))
        param_std = float(np.std(params)) if len(params) > 1 else 0.0
        
        combined = np.concatenate([type_vec, stab_vec, [param_mean, param_std]])
        
        embed[:len(combined)] = combined[:self.flow_embed_dim]
        return embed
    
    def rollout_sequence_flow(
        self, x_seq: List[np.ndarray], a_seq: List[np.ndarray],
        flow_embeds: List[np.ndarray], sample: bool = True
    ) -> Dict:
        """Rollout with flow conditioning."""
        h = np.zeros(self.belief_dim)
        
        mus = []
        logvars = []
        beliefs = []
        
        for t in range(len(x_seq)):
            h = self.gru_step(h, x_seq[t])
            z, mu, logvar = self.encode_latent(h, sample=sample)
            
            mus.append(mu)
            logvars.append(logvar)
            beliefs.append(h.copy())
        
        return {
            'mus': mus,
            'logvars': logvars,
            'beliefs': beliefs
        }


