    @pytest.mark.asyncio
    async def _check_snapshot_fallback(self, wal_dir: str, snap_file: str,
                                       allow_hash_violations: bool = False) -> list[str]:
        violations = []
        try:
            k = _make_kernel(wal_dir, snap_file)
        except Exception as exc:
            return [f"kernel_init: {type(exc).__name__}: {exc}"]
        try:
            await k.recover()
        except Exception as exc:
            # Boot failure = fallback triggered (corrupted snapshot rejected)
            return []
        vs = _check_structural_integrity(k.journal)
        if allow_hash_violations:
            # Hash violations from corrupted snapshot entries are expected —
            # they mean "detected corruption" not "silent corruption"
            vs = [v for v in vs if not v.startswith('hash_chain')]
        violations.extend(vs)
        return violations

