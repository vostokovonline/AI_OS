    # K4.5: Recovery Soundness — recover(recover(J)) = recover(J)
    # ══════════════════════════════════════════════════════════════════════════

    async def _check_idempotence(self, wal_dir: str, snap_file: str) -> list[str]:
        violations = []

        async def _do_recover() -> tuple:
            """Recover from a COPY of WAL to avoid modification cascading."""
            import shutil

            copy_dir = wal_dir + "_copy"
            if os.path.exists(copy_dir):
                shutil.rmtree(copy_dir)
            shutil.copytree(wal_dir, copy_dir)
            copy_snap = snap_file.replace(".json", "_copy.json")
            if os.path.exists(snap_file):
                shutil.copy2(snap_file, copy_snap)

            k = _make_kernel(copy_dir, copy_snap)
            try:
                await k.recover()
            except Exception as exc:
                return None, str(exc)
            return k, ""

        k1, err1 = await _do_recover()
        k2, err2 = await _do_recover()

        # Both must fail or both must succeed — no asymmetric behavior
        if k1 is None and k2 is None:
            if err1 != err2:
                violations.append(
                    f"K4.5_NonDeterministicFailure: {err1} vs {err2}")
            return violations
        if k1 is None and k2 is not None:
            violations.append(f"K4.5_NonIdempotent: first failed ({err1}), second succeeded")
            return violations
        if k1 is not None and k2 is None:
            violations.append(f"K4.5_NonIdempotent: first succeeded, second failed ({err2})")
            return violations

        # Both succeeded — compare entries
        entries1 = [
            {k: v for k, v in e.to_dict().items() if k not in ('prev_hash', 'entry_hash')}
            for e in k1.journal._entries
            if e.event not in REPAIR_EVENTS
        ]
        entries2 = [
            {k: v for k, v in e.to_dict().items() if k not in ('prev_hash', 'entry_hash')}
            for e in k2.journal._entries
            if e.event not in REPAIR_EVENTS
        ]

        if len(entries1) != len(entries2):
            violations.append(
                f"K4.5_EntryCountMismatch: r1={len(entries1)} r2={len(entries2)}")
        else:
            for i, (e1, e2) in enumerate(zip(entries1, entries2)):
                if e1.get('event') != e2.get('event') or e1.get('goal_id') != e2.get('goal_id'):
                    violations.append(f"K4.5_EntryMismatch: entry {i}")
                    break

        # Structural integrity of both — violations must be IDENTICAL
        v1 = _check_structural_integrity(k1.journal)
        v2 = _check_structural_integrity(k2.journal)
        if v1 != v2:
            violations.append(
                f"K4.5_AsymmetricIntegrity: r1={len(v1)} r2={len(v2)} "
                f"r1_only={set(v1) - set(v2)} r2_only={set(v2) - set(v1)}")
            for v in v1:
                violations.append(f"K4.5_r1: {v}")
            for v in v2:
                violations.append(f"K4.5_r2: {v}")

        return violations

