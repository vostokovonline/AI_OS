    async def _run_fuzz_trials(self, file_type: str,
                                target_getter,
                                fuzz_fn,
                                n_trials: int = 200,
                                skip_snapshot: bool = False):
        """Run fuzz mutations.

        For each trial, system must either:
          a) Explicitly fail (exception) — corruption detected
          b) Recover with structural violations — corruption detected
          c) Recover with clean integrity — mutation was benign

        Never: recover with clean integrity but silently corrupted data.
        Cases (a) and (b) are acceptable outcomes.
        Only failures of the fuzz operation itself are errors.
        """
        fuzz_rng = random.Random(RANDOM_SEED + 500)
        fuzz_errors = 0

        for trial in range(n_trials):
            seed = fuzz_rng.randint(0, 100000)
            with tempfile.TemporaryDirectory() as tmpdir:
                wal_dir = os.path.join(tmpdir, "wal")
                snap_file = os.path.join(tmpdir, "snapshot.json")
                kernel = _make_kernel(wal_dir, snap_file)
                _append_entries(kernel, 10, random.Random(seed))

                if not skip_snapshot:
                    kernel.snapshot()

                paths = target_getter(wal_dir, snap_file)
                if not paths:
                    continue

                for fpath in paths:
                    if not os.path.exists(fpath):
                        continue
                    try:
                        fuzz_fn(fpath, fuzz_rng)
                    except Exception:
                        fuzz_errors += 1
                        continue

                ok, violations, _ = await _boot_check(wal_dir, snap_file)
                # ok=True + empty violations = benign mutation (entry OK)
                # ok=True + violations = detected corruption (hash/sequence flags)
                # ok=False = explicit failure (exception during boot)
                if not ok or violations:
                    pass  # corruption detected — acceptable
                elif ok and not violations:
                    pass  # benign mutation — acceptable

        msg = (f"{file_type}: {n_trials} trials, {fuzz_errors} fuzz errors")
        assert fuzz_errors == 0, f"Fuzz operation errors: {msg}"

