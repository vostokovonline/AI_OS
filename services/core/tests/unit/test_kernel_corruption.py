"""
K4: Corruption Safety — property-based tests for segment, snapshot, and manifest corruption.

K4.1 Segment Corruption:
  Header, footer, entry hash, prev hash, seq field — each with byte-level file corruption.
  Invariant: corruption_detected > silent_corruption_accepted

K4.2 Snapshot Corruption:
  Body, metadata, checksum, entry_count — each with semantic file corruption.
  Invariant: boot_falls_back_to_wal_replay

K4.3 Manifest Corruption:
  Missing, duplicate, reordered, invalid active segment.
  Invariant: deterministic_recovery_or_explicit_failure

K4.4 Random Byte Fuzzer:
  Bit flips, insertions, deletions, truncations across all file types.
  Invariant: no_silent_corruption

K4.5 Recovery Soundness:
  recover(recover(J)) = recover(J) under all corruption scenarios.
  Invariant: recovery_idempotent
"""

