    @pytest.mark.asyncio
    async def test_k4_1_stress_all_segment_corruptions(self):
        """Run all 5 segment corruption types across 10 seeds each.

        Hash and prev_hash corruptions are expected to produce hash_chain
        violations — that proves detection works. Only structural violations
        (boot failure, non-hash integrity issues) are counted as failures.
        """
        funcs = [
            ('header_json', corrupt_segment_header_json, True),
            ('footer_json', corrupt_segment_footer_json, True),
            ('entry_hash', corrupt_entry_hash, False),
            ('prev_hash', corrupt_prev_hash, False),
            ('seq_field', corrupt_segment_seq_field, True),
        ]
        base_rng = random.Random(RANDOM_SEED + 50)
        failures = []

        for name, fn, expect_clean in funcs:
            for trial in range(10):
                seed = base_rng.randint(0, 10000)
                with tempfile.TemporaryDirectory() as tmpdir:
                    wal_dir = os.path.join(tmpdir, "wal")
                    snap_file = os.path.join(tmpdir, "snapshot.json")
                    kernel = _make_kernel(wal_dir, snap_file)
                    _append_entries(kernel, 15, random.Random(seed))
                    if name == 'footer_json':
                        kernel.snapshot()

                    fn(wal_dir)
                    ok, violations, _ = await _boot_check(wal_dir, snap_file)

                    if not ok:
                        continue  # boot failure = corruption detected, OK

                    if expect_clean:
                        # Header/footer/seq corruption should not corrupt entry data
                        if violations:
                            failures.append(f"{name}/trial={trial}: {violations}")
                    else:
                        # Hash/prev_hash corruption MUST produce hash violations
                        hash_vs = [v for v in violations if 'hash_chain' in v]
                        if not hash_vs:
                            failures.append(
                                f"{name}/trial={trial}: silent corruption — "
                                f"hash chain intact after hash corruption. "
                                f"Violations: {violations}")
                        # Non-hash violations are still failures
                        non_hash_vs = [v for v in violations if 'hash_chain' not in v]
                        if non_hash_vs:
                            failures.append(
                                f"{name}/trial={trial}: non-hash violations: {non_hash_vs}")

        assert len(failures) == 0, \
            f"{len(failures)} violations:\n" + "\n".join(failures[:20])

