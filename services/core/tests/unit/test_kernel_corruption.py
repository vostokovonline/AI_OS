# ── Helpers ──────────────────────────────────────────────────────────────────


def _make_kernel(wal_dir: str, snap_file: str) -> ExecutionKernel:
    os.makedirs(wal_dir, exist_ok=True)
    return ExecutionKernel(
        config=ExecutionConfig(
            wal_path=wal_dir,
            snapshot_path=snap_file,
        )
    )


def _append_entries(kernel: ExecutionKernel, count: int,
                    rng: random.Random) -> list[JournalEntry]:
    """Append N entries with hash chain (via journal.append())."""
    entries = []
    for i in range(count):
        goal_id = f"goal_{rng.randint(0, 3)}"
        event = rng.choice(['DISPATCHED', 'STARTED', 'COMPLETED', 'LEASE_ISSUED'])
        e = JournalEntry(
            event=event,
            goal_id=goal_id,
            execution_id=f"{goal_id}:exec:{i}",
            lease_id=f"lease_{goal_id}",
            timestamp=time.time() + i * 0.1,
        )
        kernel.journal.append(e)
        entries.append(e)
    return entries


def _read_segment_files(wal_dir: str) -> list[str]:
    if not os.path.exists(wal_dir):
        return []
    return sorted([
        os.path.join(wal_dir, f) for f in os.listdir(wal_dir)
        if f.endswith('.wal') and f != 'manifest.json'
    ])


def _read_manifest(wal_dir: str) -> dict:
    mpath = os.path.join(wal_dir, 'manifest.json')
    if not os.path.exists(mpath):
        return {}
    with open(mpath) as f:
        return json.load(f)


def _write_manifest(wal_dir: str, manifest: dict):
    mpath = os.path.join(wal_dir, 'manifest.json')
    tmp = mpath + '.tmp'
    with open(tmp, 'w') as f:
        json.dump(manifest, f, indent=2, sort_keys=True)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, mpath)


def _read_segment_raw(wal_dir: str) -> bytes:
    files = _read_segment_files(wal_dir)
    if not files:
        return b''
    with open(files[-1], 'rb') as f:
        return f.read()


def _read_snapshot(snap_file: str) -> dict:
    if not os.path.exists(snap_file):
        return {}
    with open(snap_file) as f:
        return json.load(f)


def _write_snapshot(snap_file: str, data: dict):
    tmp = snap_file + '.tmp'
    with open(tmp, 'w') as f:
        json.dump(data, f, indent=2, sort_keys=True)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, snap_file)


# ── Structural integrity check (hash_chain + sequence only) ──────────────────
# NOTE: we intentionally skip lifecycle verification because random entries
# generated by _append_entries() don't follow the state machine.
# Hash chain + sequence are the structural invariants that matter for K4.


def _check_structural_integrity(journal) -> list[str]:
    """Check hash chain + sequence + no duplicate entry_ids.

    Returns list of violation strings (empty = OK).
    """
    violations = []
    verifier = IntegrityVerifier()

    hash_errors = verifier.verify_hash_chain(journal)
    for e in hash_errors:
        violations.append(f"hash_chain: {e.detail}")

    seq_errors = verifier.verify_sequence(journal)
    for e in seq_errors:
        violations.append(f"sequence: {e.detail}")

    seen = set()
    for entry in journal._entries:
        if entry.entry_id in seen:
            violations.append(f"duplicate_entry_id: {entry.entry_id}")
        seen.add(entry.entry_id)

    return violations


# ── Boot Integrity Check ─────────────────────────────────────────────────────


async def _boot_check(
    wal_dir: str,
    snap_file: str,
    expect_recovery_fail: bool = False,
) -> tuple[bool, list[str], str]:
    """Boot from (possibly corrupted) WAL and check structural invariants.

    Returns (boot_succeeded, violations, method_or_error).
    """
    violations = []
    try:
        k = _make_kernel(wal_dir, snap_file)
    except Exception as exc:
        if expect_recovery_fail:
            return False, [], f"make_kernel_error:{type(exc).__name__}"
        return False, [f"make_kernel_error: {type(exc).__name__}: {exc}"], ""

    try:
        await k.recover()
    except Exception as exc:
        if expect_recovery_fail:
            return False, [], f"expected:{type(exc).__name__}"
        return False, [f"recovery_error: {type(exc).__name__}: {exc}"], ""

    # Structural integrity
    violations.extend(_check_structural_integrity(k.journal))
    return True, violations, ""


# ── K4.1: Segment Corruption ─────────────────────────────────────────────────


def _find_entry_lines(raw: bytes) -> list[int]:
    """Return line indices containing journal entries (not _wal_meta)."""
    lines = raw.split(b'\n')
    return [i for i, line in enumerate(lines)
            if line.strip() and b'"_wal_meta"' not in line]


def corrupt_segment_header_json(wal_dir: str):
    """Remove closing brace from segment_header — invalid JSON."""
    files = _read_segment_files(wal_dir)
    if not files:
        return
    with open(files[-1], 'rb') as f:
        raw = f.read()
    lines = raw.split(b'\n')
    for i, line in enumerate(lines):
        if b'"_wal_meta"' in line and b'segment_header' in line:
            lines[i] = line.rstrip(b'}')
            break
    with open(files[-1], 'wb') as f:
        f.write(b'\n'.join(lines))


def corrupt_segment_footer_json(wal_dir: str):
    """Insert duplicate key in segment_footer — invalid JSON."""
    files = _read_segment_files(wal_dir)
    if not files:
        return
    with open(files[-1], 'rb') as f:
        raw = f.read()
    lines = raw.split(b'\n')
    for i in range(len(lines) - 1, -1, -1):
        if b'"_wal_meta"' in lines[i] and b'segment_footer' in lines[i]:
            lines[i] = lines[i].replace(b'entry_count', b'entry_count, "entry_count')
            break
    with open(files[-1], 'wb') as f:
        f.write(b'\n'.join(lines))


def corrupt_entry_hash(wal_dir: str):
    """Corrupt entry_hash INSIDE the payload dict (what recover_from_wal reads)."""
    files = _read_segment_files(wal_dir)
    if not files:
        return
    with open(files[-1], 'rb') as f:
        raw = f.read()
    lines = raw.split(b'\n')
    entry_indices = [i for i in _find_entry_lines(raw) if i < len(lines)]
    if not entry_indices:
        return
    idx = random.Random(RANDOM_SEED + 100).choice(entry_indices)
    line = lines[idx]
    # Find the last occurrence of entry_hash (which is inside payload)
    # The line structure with sort_keys=True is:
    # {"entry_hash": "TOP", ..., "payload": {"entry_hash": "PAYLOAD", ...}, ...}
    # We NEED to corrupt the PAYLOAD one
    parts = line.split(b'"entry_hash": "')
    if len(parts) >= 3:
        # parts[0] = ..., parts[1] = top hash..., parts[2] = payload hash...
        # Corrupt the payload's entry_hash (third occurrence)
        payload_part = parts[-1]
        payload_corrupted = b'PAYLOAD_CORRUPTED_' + payload_part
        line = b'"entry_hash": "'.join(parts[:-1]) + b'"entry_hash": "' + payload_corrupted
    elif len(parts) == 2:
        # Only one entry_hash — top level (no payload?), corrupt it
        line = parts[0] + b'"entry_hash": "CORRUPTED_' + parts[1]
    lines[idx] = line
    with open(files[-1], 'wb') as f:
        f.write(b'\n'.join(lines))


def corrupt_prev_hash(wal_dir: str):
    """Corrupt prev_hash inside the payload dict."""
    files = _read_segment_files(wal_dir)
    if not files:
        return
    with open(files[-1], 'rb') as f:
        raw = f.read()
    lines = raw.split(b'\n')
    entry_indices = [i for i in _find_entry_lines(raw) if i < len(lines)]
    if len(entry_indices) < 2:
        return
    idx = random.Random(RANDOM_SEED + 101).choice(entry_indices[1:])
    line = lines[idx]
    # With sort_keys=True, prev_hash appears: 1st inside payload, 2nd at top level.
    # We need to corrupt the 1st (payload) occurrence since recover_from_wal reads payload.
    parts = line.split(b'"prev_hash": "')
    if len(parts) >= 3:
        # parts[1] = payload's prev_hash value + payload closing + ', "prev_hash": "'
        payload_part = parts[1]
        payload_corrupted = b'PAYLOAD_BROKEN_' + payload_part
        parts[1] = payload_corrupted
        line = b'"prev_hash": "'.join(parts)
    elif len(parts) == 2:
        line = parts[0] + b'"prev_hash": "BROKEN_' + parts[1]
    lines[idx] = line
    with open(files[-1], 'wb') as f:
        f.write(b'\n'.join(lines))


def corrupt_segment_seq_field(wal_dir: str):
    """Modify seq in segment_header."""
    files = _read_segment_files(wal_dir)
    if not files:
        return
    with open(files[-1], 'rb') as f:
        raw = f.read()
    lines = raw.split(b'\n')
    for i, line in enumerate(lines):
        if b'"_wal_meta"' in line and b'segment_header' in line:
            lines[i] = line.replace(b'"seq": 1', b'"seq": 99999')
            break
    with open(files[-1], 'wb') as f:
        f.write(b'\n'.join(lines))


# ── K4.2: Snapshot Corruption ────────────────────────────────────────────────


def corrupt_snapshot_body(snap_file: str):
    """Corrupt a random entry's goal_id in snapshot."""
    data = _read_snapshot(snap_file)
    if not data or 'entries' not in data or not data['entries']:
        return
    idx = random.Random(RANDOM_SEED + 200).randint(0, len(data['entries']) - 1)
    data['entries'][idx]['goal_id'] += '_corrupted'
    _write_snapshot(snap_file, data)


def corrupt_snapshot_metadata(snap_file: str):
    """Corrupt last_lsn and last_entry_hash to invalid values."""
    data = _read_snapshot(snap_file)
    if not data:
        return
    data['last_lsn'] = 'CORRUPTED-LSN-00000'
    data['last_entry_hash'] = '0' * 64
    _write_snapshot(snap_file, data)


def corrupt_snapshot_checksum(snap_file: str):
    """Corrupt last_entry_hash (checksum mismatch)."""
    data = _read_snapshot(snap_file)
    if not data:
        return
    data['last_entry_hash'] = hashlib.sha256(b'corrupted').hexdigest()
    _write_snapshot(snap_file, data)


def corrupt_snapshot_entry_count(snap_file: str):
    """Set entry_count to wrong value."""
    data = _read_snapshot(snap_file)
    if not data:
        return
    data['entry_count'] = data.get('entry_count', 0) + 50
    _write_snapshot(snap_file, data)


# ── K4.3: Manifest Corruption ────────────────────────────────────────────────


def corrupt_manifest_missing_segment(wal_dir: str):
    manifest = _read_manifest(wal_dir)
    if not manifest or 'segments' not in manifest or len(manifest['segments']) < 2:
        return
    manifest['segments'].pop(0)
    _write_manifest(wal_dir, manifest)


def corrupt_manifest_duplicate_segment(wal_dir: str):
    manifest = _read_manifest(wal_dir)
    if not manifest or 'segments' not in manifest or not manifest['segments']:
        return
    manifest['segments'].append(dict(manifest['segments'][0]))
    _write_manifest(wal_dir, manifest)


def corrupt_manifest_reordered_segments(wal_dir: str):
    manifest = _read_manifest(wal_dir)
    if not manifest or 'segments' not in manifest or len(manifest['segments']) < 2:
        return
    manifest['segments'] = list(reversed(manifest['segments']))
    _write_manifest(wal_dir, manifest)


def corrupt_manifest_invalid_active(wal_dir: str):
    manifest = _read_manifest(wal_dir)
    if not manifest or 'segments' not in manifest or not manifest['segments']:
        return
    seg = dict(manifest['segments'][-1])
    seg['seq'] = 99999
    manifest['segments'].append(seg)
    _write_manifest(wal_dir, manifest)


# ── K4.4: Fuzz Helpers ────────────────────────────────────────────────────────


def _fuzz_file_bit_flip(path: str, rng: random.Random):
    with open(path, 'rb') as f:
        data = f.read()
    if len(data) < 2:
        return
    offset = rng.randint(0, len(data) - 1)
    byte_val = data[offset]
    bit = 1 << rng.randint(0, 7)
    data = data[:offset] + bytes([byte_val ^ bit]) + data[offset + 1:]
    with open(path, 'wb') as f:
        f.write(data)


def _fuzz_file_insert(path: str, rng: random.Random):
    with open(path, 'rb') as f:
        data = f.read()
    if not data:
        return
    offset = rng.randint(0, len(data) - 1)
    data = data[:offset] + bytes([rng.randint(0, 255)]) + data[offset:]
    with open(path, 'wb') as f:
        f.write(data)


def _fuzz_file_delete(path: str, rng: random.Random):
    with open(path, 'rb') as f:
        data = f.read()
    if len(data) < 4:
        return
    offset = rng.randint(0, len(data) - 1)
    data = data[:offset] + data[offset + 1:]
    with open(path, 'wb') as f:
        f.write(data)


def _fuzz_file_truncate(path: str, rng: random.Random):
    with open(path, 'rb') as f:
        data = f.read()
    if len(data) < 10:
        return
    ratio = rng.uniform(0.05, 0.95)
    keep = max(int(len(data) * ratio), 1)
    with open(path, 'wb') as f:
        f.write(data[:keep])


